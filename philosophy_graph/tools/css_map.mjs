#!/usr/bin/env node
// Карта стилей: что лежит в блоке <style>, по главам и правилам.
//
// Порядок в таблице стилей — часть смысла: при равной весомости побеждает
// последнее правило. Поэтому карта строится не как множество, а как
// последовательность, и главы режутся ПО ГРАНИЦАМ, а не по темам вразброс.
// Тогда склейка глав в порядке подключения даёт исходный текст знак в знак,
// и каскад заведомо не меняется.
import fs from 'node:fs';

// Главы задаются ЯКОРЯМИ — точным куском текста, с которого глава
// начинается. Не номерами строк: вставка в начало сдвинула бы всё.
export const ГЛАВЫ = [
  ['01-base',        null,                                        'основа: тело, полотно, панель контроля, подсказки'],
  ['02-legend',      '/* Стили для сворачиваемых секций */',       'легенда: сворачиваемые разделы, галочки, поиск'],
  ['03-modal-common', '/* ============================================ */\n    /* ОБЩИЕ СТИЛИ ДЛЯ МОДАЛЬНЫХ ОКОН',           'общая кожа модальных окон'],
  ['04-modal-philosopher', '/* ============================================ */\n    /* СПЕЦИФИЧНЫЕ СТИЛИ ДЛЯ ОКНА ФИЛОСОФА', 'окно философа и окно описаний пути'],
  ['05-path',        '/* Панель поиска пути - с возможностью сворачивания */', 'панель поиска пути и её узлы'],
  ['06-chronology',  '/* Стили для режима хронологии */',          'хронология, предупреждения, поля поиска'],
  ['07-stats',       '/* ============================================ */\n    /* МОДАЛЬНОЕ ОКНО РАСШИРЕННОЙ СТАТИСТИКИ',      'окно статистики: панель, содержимое, метрики'],
  ['08-stats-results', '/* ============================================ */\n    /* ОТОБРАЖЕНИЕ РЕЗУЛЬТАТОВ',                  'карточки и таблицы итогов, кнопки, прогресс'],
  ['09-tension',     '/* ============================================ */\n    /* СПЕЦИФИЧНЫЕ СТИЛИ ДЛЯ ИНДЕКСА НАПРЯЖЕНИЯ',   'шкала напряжения и разделы деталей'],
  ['10-forms',       '/* ---- поля формы ---- */',                 'формы правки: поля, кнопки, списки, режим правки'],
];

const ВХОД = process.argv[2] || '/home/claude/build/orig_v3.html';
const ВЫХОД = process.argv[3] || '/home/claude/css_map.json';

// Программа служит двум делам: сама строит карту и отдаёт перечень глав
// разрезателю. При ввозе ничего не считаем — иначе он споткнётся о путь.
const самостоятельно = process.argv[1] && process.argv[1].endsWith('css_map.mjs');
if (самостоятельно) {
const html = fs.readFileSync(ВХОД, 'utf8');
const a = html.indexOf('<style>'), b = html.indexOf('</style>');
if (a < 0 || b < 0) { console.error('нет блока стилей'); process.exit(1); }
const css = html.slice(a + 7, b);


// границы глав
const границы = [];
for (const [имя, якорь, описание] of ГЛАВЫ) {
  if (якорь === null) { границы.push({ имя, описание, от: 0 }); continue; }
  const i = css.indexOf(якорь);
  if (i < 0) { console.error('якорь не найден: ' + якорь); process.exit(1); }
  границы.push({ имя, описание, от: i });
}
for (let i = 0; i < границы.length; i++)
  границы[i].до = i + 1 < границы.length ? границы[i + 1].от : css.length;

// Разбор правил. Перед разбором ВЫЧЁРКИВАЮТСЯ пояснения и строковые
// постоянные: фигурная скобка внутри `content: "}"` иначе сбивает счёт
// вложенности, и разбор уходит вразнос (проверено — съел два гигабайта).
function очистить(t) {
  return t
    .replace(/\/\*[\s\S]*?\*\//g, m => ' '.repeat(m.length))
    .replace(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/g, m => ' '.repeat(m.length));
}

function правила(исходный, сдвиг) {
  const текст = очистить(исходный);
  const out = [];
  let глубина = 0, начало = 0, вМедиа = null;
  for (let i = 0; i < текст.length; i++) {
    const c = текст[i];
    if (c === '{') {
      const сел = исходный.slice(начало, i).trim().replace(/\s+/g, ' ');
      if (глубина === 0) {
        if (/^@(media|supports|container)/.test(сел)) вМедиа = сел;
        else if (сел) out.push({ селектор: сел, где: сдвиг + начало, медиа: null });
      } else if (глубина === 1 && вМедиа && сел) {
        out.push({ селектор: сел, где: сдвиг + начало, медиа: вМедиа });
      }
      глубина++; начало = i + 1;
    } else if (c === '}') {
      глубина = Math.max(0, глубина - 1);
      if (глубина === 0) вМедиа = null;
      начало = i + 1;
    } else if (c === ';' && глубина === 0) {
      начало = i + 1;
    }
  }
  return out;
}

const главы = границы.map(г => {
  const текст = css.slice(г.от, г.до);
  const пр = правила(текст, г.от);
  return {
    имя: г.имя, описание: г.описание,
    строк: текст.split('\n').length - 1,
    знаков: текст.length,
    правил: пр.length,
    вМедиа: пр.filter(p => p.медиа).length,
    селекторы: пр.map(p => p.селектор),
  };
});

// повторы: один селектор в разных главах — законный приём каскада,
// но знать о нём надо: перестановка глав такое поведение изменит
const где = new Map();
for (const г of главы)
  for (const с of г.селекторы) {
    if (!где.has(с)) где.set(с, new Set());
    где.get(с).add(г.имя);
  }
const межглавные = [...где].filter(([, s]) => s.size > 1)
  .map(([с, s]) => ({ селектор: с, главы: [...s] }));

const итог = {
  меры: { знаков: css.length, строк: css.split('\n').length - 1,
          правил: главы.reduce((a, г) => a + г.правил, 0), глав: главы.length },
  главы: главы.map(({ селекторы, ...rest }) => ({ ...rest, примеры: селекторы.slice(0, 6) })),
  межглавныеПовторы: межглавные,
};
fs.writeFileSync(ВЫХОД, JSON.stringify(итог, null, 1));

console.log(`стили: ${итог.меры.знаков} знаков, ${итог.меры.строк} строк, ` +
  `${итог.меры.правил} правил, ${итог.меры.глав} глав`);
for (const г of главы)
  console.log(`  ${г.имя.padEnd(20)} ${String(г.строк).padStart(5)} стр  ` +
    `${String(г.правил).padStart(4)} правил  ${г.описание}`);
console.log(`селекторов, встречающихся в разных главах: ${межглавные.length}`);

}
