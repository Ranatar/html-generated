#!/usr/bin/env node
// Эталоны приборов — первый слой приёмки.
//
// Что это. Приёмка сегодня сравнивает две живые страницы: сборку и
// одностраничный исходник. Пока обе действующие, это лучший из способов —
// обе идут в одних условиях, и расхождение означает разницу поведения.
// Но исходник когда-нибудь отпустят, и сравнивать станет не с чем.
//
// Эталон — снимок, объявленный ожидаемым. Он отвечает на вопрос «стало ли
// иначе, чем было», и этого довольно, чтобы поймать случайную поломку.
// Он НЕ отвечает на вопрос «правильно ли»: снятый с испорченной стороны,
// он закрепит поломку как норму. Три таких случая уже были — разбор
// собственного onclick в подсветке вкладок, пустая проверка подсветки узла,
// пропавшая кнопка «Нормировать». Поэтому это только ПЕРВЫЙ слой; второй —
// утверждения о должном — впереди.
//
// ГЛАВНОЕ ПРАВИЛО ЗАМОРОЗКИ: эталоном может стать лишь то, что
// ВОСПРОИЗВОДИТСЯ. Поэтому утверждение требует ДВУХ снимков одной и той же
// стороны и отказывается, если они разошлись. Раскладка графа считает шаги
// по реальному времени, координаты у двух прогонов разные — приборы,
// завязанные на неё, замораживать нельзя, и они помечены явно.
//
//   node tools/baseline.mjs утвердить <прибор> <снимок1> <снимок2>
//   node tools/baseline.mjs состав
//   node tools/baseline.mjs проверить <прибор> <новый снимок>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { объяснить } from './snapshot.mjs';

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ПАПКА = path.join(КОРЕНЬ, 'baseline');
const СВОД = path.join(ПАПКА, 'manifest.json');

// Кого можно замораживать, а кого нет — и почему. Это не список файлов,
// это решение, и оно должно быть записано словами.
const ПРИБОРЫ = {
  sweep_all:   { заморозка: true,  зачем: 'полный обход обработчиков; раскладки не касается' },
  compare:     { заморозка: true,  зачем: '39 видов, окна, фильтры, пути, вход' },
  probe6:      { заморозка: true,  зачем: 'правка при вынесенной базе' },
  probe7:      { заморозка: true,  зачем: 'сохранность правок' },
  probe8:      { заморозка: true,  зачем: 'переключатель заморозки' },
  css_probe:   { заморозка: true,  зачем: 'вычисленные стили' },
  graph_probe: { заморозка: false, зачем: 'координаты узлов у двух прогонов разные — выбор узла и содержимое подсказки гуляют' },
  probe4:      { заморозка: false, зачем: 'то же: замер показал расхождение снимка «узкий экран» между двумя прогонами исходника' },
  probe5:      { заморозка: false, зачем: 'ctrl-клик и карта сходства считаются от раскладки' },
};

fs.mkdirSync(ПАПКА, { recursive: true });
const свод = fs.existsSync(СВОД) ? JSON.parse(fs.readFileSync(СВОД, 'utf8')) : {};

const [, , команда, а1, а2, а3] = process.argv;

function ключи(о) { return Object.keys(о).filter(k => !k.startsWith('__')); }

function разница(a, b) {
  const общие = ключи(a).filter(k => k in b);
  const разошлось = общие.filter(k =>
    JSON.stringify(a[k]) !== JSON.stringify(b[k]));
  const толькоA = ключи(a).filter(k => !(k in b));
  const толькоB = ключи(b).filter(k => !(k in a));
  return { сверено: общие.length, разошлось, толькоA, толькоB };
}

if (команда === 'утвердить') {
  const прибор = а1;
  const сведения = ПРИБОРЫ[прибор];
  if (!сведения) { console.error('неизвестный прибор: ' + прибор); process.exit(1); }
  if (!сведения.заморозка) {
    console.error(`${прибор} замораживать нельзя: ${сведения.зачем}`);
    process.exit(1);
  }
  if (!а2 || !а3) { console.error('нужны ДВА снимка одной стороны — иначе нечем доказать воспроизводимость'); process.exit(1); }
  const п1 = JSON.parse(fs.readFileSync(а2, 'utf8'));
  const п2 = JSON.parse(fs.readFileSync(а3, 'utf8'));
  const р = разница(п1, п2);
  if (р.разошлось.length || р.толькоA.length || р.толькоB.length) {
    console.error(`два прогона РАЗОШЛИСЬ (${р.разошлось.length} снимков) — замораживать нечего:`);
    р.разошлось.slice(0, 6).forEach(k => console.error('   ' + k));
    process.exit(1);
  }
  const ошибок = (п1.__errs || []).length;
  if (ошибок) {
    console.error(`в снимке ${ошибок} ошибок страницы — такое эталоном не объявляют`);
    process.exit(1);
  }
  fs.writeFileSync(path.join(ПАПКА, прибор + '.json'), JSON.stringify(п1, null, 1));
  свод[прибор] = {
    снимков: р.сверено,
    утверждён: new Date().toISOString().slice(0, 19).replace('T', ' '),
    зачем: сведения.зачем,
    проверка: 'два прогона одной стороны совпали',
  };
  fs.writeFileSync(СВОД, JSON.stringify(свод, null, 1));
  console.log(`${прибор}: эталон утверждён, снимков ${р.сверено}`);

} else if (команда === 'проверить') {
  const прибор = а1;
  const файл = path.join(ПАПКА, прибор + '.json');
  if (!fs.existsSync(файл)) { console.error('нет эталона для ' + прибор); process.exit(1); }
  const эт = JSON.parse(fs.readFileSync(файл, 'utf8'));
  const нов = JSON.parse(fs.readFileSync(а2, 'utf8'));
  const р = разница(эт, нов);
  const ошибок = (нов.__errs || []).length;
  console.log(`${прибор}: сверено ${р.сверено}, ` +
    `совпало ${р.сверено - р.разошлось.length}, разошлось ${р.разошлось.length}` +
    (ошибок ? `, ОШИБОК СТРАНИЦЫ ${ошибок}` : ''));
  for (const k of р.разошлось.slice(0, 20)) {
    // Третий слой: снимок сам говорит ГДЕ разошёлся — поле или кусок разметки
    const разбор = объяснить(k, эт[k], нов[k]);
    console.log(разбор || `  ✗ ${k}`);
  }
  if (р.толькоA.length) console.log('  нет в новом снимке: ' + р.толькоA.slice(0, 8).join(', '));
  if (р.толькоB.length) console.log('  нет в эталоне: ' + р.толькоB.slice(0, 8).join(', '));
  process.exit(р.разошлось.length || р.толькоA.length || р.толькоB.length || ошибок ? 1 : 0);

} else {
  console.log('приборы и их состояние:\n');
  for (const [имя, с] of Object.entries(ПРИБОРЫ)) {
    const есть = свод[имя];
    const метка = !с.заморозка ? 'НЕ ЗАМОРАЖИВАЕТСЯ'
      : есть ? `эталон от ${есть.утверждён}, снимков ${есть.снимков}` : 'эталона ещё нет';
    console.log(`  ${имя.padEnd(12)} ${метка}`);
    console.log(`  ${' '.repeat(12)} ${с.зачем}`);
  }
  console.log('\nЭталон отвечает «стало ли иначе», а не «правильно ли».');
  console.log('Приборы без заморозки продолжают сверяться с одностраничным исходником.');
}
