#!/usr/bin/env python3
"""map_tree.json → читаемая карта модульного дерева."""
import json, sys, collections

вход = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/map_tree.json'
выход = sys.argv[2] if len(sys.argv) > 2 else '/home/claude/map_tree.md'
d = json.load(open(вход, encoding='utf-8'))
м = d['меры']
L = []
w = L.append

w('# Карта модульного дерева `philosophy_graph`\n')
w(f"""Составлена **по собранному дереву**, а не по одностраничному исходнику:
{м['модулей']} модулей, {м['строк']} строк, {м['объявлений']} объявлений,
{м['вывозов']} вывозов, {м['рёбер']} рёбер ввоза. Составлено {м['составлено']}.

Зачем отдельно от карты глобальных сущностей. Та описывает единый файл — 746
сущностей в одной области видимости — и нужна разбивке: по ней считается
раскладка. Но у модульного дерева есть свойства, которых у единого файла нет
вовсе: кто у кого что ввозит, какие имена вывезены впустую, насколько плотно
модули лезут в общие пространства, есть ли круги. И эта карта переживёт
одностраничную версию, когда её отпустят.\n""")

w('## Что держит дом\n')
w('Входящая степень — из скольких модулей ввозят этот.\n')
w('| Модуль | Ввозят из него |')
w('|---|---|')
for x in d['держатДом'][:12]:
    w(f"| `{x['модуль']}` | {x['ввозятИзНего']} |")

w('\n## Самые востребованные имена\n')
w('| Имя | В скольких модулях ввозится |')
w('|---|---|')
for x in d['самыеВостребованные'][:15]:
    w(f"| `{x['имя']}` | {x['ввозятМодулей']} |")

w('\n## Общие пространства имён\n')
w('| Пространство | Полей | Самое востребованное поле | В скольких модулях |')
w('|---|---|---|---|')
for н, v in d['пространства'].items():
    первое = v['самые'][0] if v['самые'] else {'поле': '—', 'модулей': 0}
    w(f"| `{н}` | {v['полей']} | `{первое['поле']}` | {первое['модулей']} |")

w('\n## Круги в графе ввозов\n')
if not d['круги']:
    w('Кругов нет.\n')
else:
    for c in d['круги']:
        w(f"**Круговая группа из {len(c)} модулей.** Это не поломка: тела модулей —\n"
          f"почти одни объявления, поэтому взаимный ввоз безопасен, и приёмка это\n"
          f"подтверждает. Но круг такого размера — знак, что граница между областями\n"
          f"проведена не по живому: половина дерева ввозит друг друга.\n")
        w('\nМодули круга: ' + ', '.join(f'`{x}`' for x in c) + '\n')

w('\n## Вывоз впустую и мёртвые сущности\n')
w(f"""Различать обязательно. **Лишний вывоз** — имя вывезено, никем не ввозится,
но внутри своего модуля работает: разбивка вывозит все собственные имена
подряд, поэтому таких много ({м['лишнихВывозов']}), и это шум в списке вывоза,
а не мёртвый код. **Мёртвая сущность** — имя не помянуто нигде: ни снаружи, ни
внутри своего модуля. Таких сейчас **{м['мёртвыхСущностей']}**.

Отдельно считаются имена, которые держатся только приборами приёмки
({м.get('держатсяПриборами', 0)}): в дереве они выглядят мёртвыми, а на деле
их ввозят измерительные программы.\n""")
if d.get('держатсяТолькоПриборами'):
    w('| Имя | Модуль |')
    w('|---|---|')
    for x in d['держатсяТолькоПриборами']:
        w(f"| `{x['имя']}` | `{x['модуль']}` |")

w('\n## Модули\n')
w('| Модуль | Строк | Объявлений | Вывозит | Ввозит из | Пространства |')
w('|---|---|---|---|---|---|')
for x in d['модули']:
    нс = ', '.join(f"{k}:{v}" for k, v in (x.get('вНС') or {}).items()) or '—'
    w(f"| `{x['путь']}` | {x['строк']} | {x['объявлений']} | {x['вывозит']} | {x['ввозитИз']} | {нс} |")

w('\n## Состав модулей\n')
w('Что в модуле ОБЪЯВЛЕНО. В JSON это лежало с самого начала (поле `свои`),\n'
  'но в читаемый вид не выводилось — упущение, а не замысел: состав и есть\n'
  'самое нужное, когда ищешь, где живёт сущность.\n')
for x in d['модули']:
    if not x.get('свои'):
        continue
    w(f"\n### `{x['путь']}` — {x['строк']} строк, объявлений {len(x['свои'])}\n")
    w('| Имя | Вид | Строк | Вывозится |')
    w('|---|---|---|---|')
    вывоз = set(x['вывоз'])
    for e in sorted(x['свои'], key=lambda e: -e['строк']):
        w(f"| `{e['имя']}` | {e['вид']} | {e['строк']} | "
          f"{'да' if e['имя'] in вывоз else '—'} |")

w('\n## Ввоз по модулям\n')
for x in d['модули']:
    if not x['ввоз']:
        continue
    w(f"\n### `{x['путь']}`\n")
    for и in x['ввоз']:
        w(f"- из `{и['откуда']}`: " + (', '.join(f'`{n}`' for n in и['имена']) or '_ради побочного действия_'))
    if x['чащеВсего']:
        w('\nЧаще всего поминает: ' +
          ', '.join(f"`{c['имя']}`×{c['раз']}" for c in x['чащеВсего']))

open(выход, 'w', encoding='utf-8').write('\n'.join(L))
print('записано', выход)
