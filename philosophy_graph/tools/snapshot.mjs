// Третий слой приёмки: снимок, умеющий сказать ГДЕ разошлось.
//
// Беда первых двух слоёв: хеш отвечает «разошлось», но не «что». Пока рядом
// есть вторая живая страница, можно прогнать обе и посмотреть глазами — я так
// и делал, отдельными разбирающими прогонами, и всякий раз это стоило ещё
// одного захода. С эталоном второй стороны нет вовсе.
//
// Лечение простое: считать не один хеш на снимок, а ещё и по куску. Тогда при
// расхождении видно, в какой доле разметки оно случилось, и искать надо не по
// пятидесяти тысячам знаков, а по паре тысяч. Кусков немного (32), поэтому
// снимки почти не толстеют.
//
// Короткие значения (до 300 знаков) хранятся ЦЕЛИКОМ — им разбор не нужен,
// достаточно показать оба.

export const КУСКОВ = 32;

// Источник страничной части: строкой, потому что исполняется в браузере.
export const ХЕШ = `(function (s) {
  s = String(s)
    .replace(/\\son[a-z]+\\s*=\\s*"[^"]*"/gi, '')
    .replace(/\\sdata-act-[a-z]+\\s*=\\s*"[^"]*"/gi, '')
    .replace(/\\sdata-a\\d+\\s*=\\s*"[^"]*"/gi, '')
    .replace(/\\sdata-sweep[a-z-]*\\s*=\\s*"[^"]*"/gi, '');
  s = s.replace(/>\\s+</g, '><').replace(/\\s+/g, ' ').trim();
  var хеш = function (t) {
    var h = 7 >>> 0;
    for (var i = 0; i < t.length; i++) h = (Math.imul(h, 31) + t.charCodeAt(i)) >>> 0;
    return h;
  };
  var ч = [], шаг = Math.ceil(s.length / ${КУСКОВ}) || 1;
  for (var i = 0; i < s.length; i += шаг) ч.push(хеш(s.slice(i, i + шаг)));
  // Накопительные хеши: хеш ВСЕГО НАЧАЛА до каждой отметки. Независимые
  // куски бесполезны, когда длина изменилась: вставка девяти знаков в
  // начале сдвигает все границы, и «разошлось» показывают все 32 куска.
  // По началам же видно, до какого места текст ещё совпадал.
  var п = [], отметка = Math.ceil(s.length / ${КУСКОВ}) || 1;
  for (var k = отметка; k <= s.length; k += отметка) п.push(хеш(s.slice(0, k)));
  var о = { h: хеш(s), n: s.length, ч: ч, п: п };
  if (s.length <= 300) о.v = s;
  return о;
})`;

// Сравнение двух снимков с объяснением. Терпит снимки без кусков — старые
// эталоны от этого не ломаются, просто объяснения по ним не будет.
export function сравнить(а, б) {
  if (JSON.stringify(а) === JSON.stringify(б)) return { равно: true };
  if (а == null || б == null) return { равно: false, почему: 'снимка нет с одной стороны' };

  // Снимки полного обхода — это строка полей через «|»: показываем, КАКОЕ
  // поле разъехалось, а не всю строку целиком.
  if (typeof а === 'string' && typeof б === 'string') {
    const па = а.split('|'), пб = б.split('|');
    const разные = [];
    for (let i = 0; i < Math.max(па.length, пб.length); i++)
      if (па[i] !== пб[i]) разные.push(i);
    if (!разные.length) return { равно: false, почему: 'строки разные, а поля те же' };
    const i = разные[0];
    return { равно: false, почему: `поле ${i + 1} из ${па.length}: ` +
      `«${(па[i] || '').slice(0, 40)}» → «${(пб[i] || '').slice(0, 40)}»` +
      (разные.length > 1 ? `; всего разных полей ${разные.length}` : '') };
  }
  if (а.v !== undefined || б.v !== undefined)
    return { равно: false, почему: 'значения целиком', было: а.v, стало: б.v };
  // Сперва по началам: они переживают сдвиг длины
  if (Array.isArray(а.п) && Array.isArray(б.п)) {
    const отмА = Math.ceil(а.n / КУСКОВ) || 1;
    let совпало = 0;
    while (совпало < Math.min(а.п.length, б.п.length) && а.п[совпало] === б.п[совпало]) совпало++;
    const от = совпало * отмА, до = Math.min(а.n, от + отмА);
    return { равно: false,
      почему: `первое расхождение между знаками ${от} и ${до} (из ${а.n})` +
        (а.n !== б.n ? `; длина ${а.n} → ${б.n}` : ''),
      диапазон: [от, до] };
  }
  if (!Array.isArray(а.ч) || !Array.isArray(б.ч))
    return { равно: false, почему: `хеш ${а.h}≠${б.h}, знаков ${а.n}≠${б.n}; ` +
      'кусков в снимке нет — объяснить нечем, переутвердите эталон' };

  const шагА = Math.ceil(а.n / КУСКОВ) || 1;
  const разные = [];
  for (let i = 0; i < Math.max(а.ч.length, б.ч.length); i++)
    if (а.ч[i] !== б.ч[i]) разные.push(i);

  if (!разные.length)
    return { равно: false, почему: `куски совпали, а целое нет — длина ${а.n}≠${б.n}` };

  const первый = разные[0];
  const от = первый * шагА, до = Math.min(а.n, от + шагА);
  return {
    равно: false,
    почему: `разошлось в куске ${первый + 1} из ${а.ч.length} ` +
      `(знаки ${от}–${до} из ${а.n}); всего разных кусков ${разные.length}` +
      (а.n !== б.n ? `; длина ${а.n} → ${б.n}` : ''),
    кусок: первый, диапазон: [от, до],
  };
}

// Печать разбора одной строки сверки — общая для всех приборов.
export function объяснить(имя, а, б) {
  const р = сравнить(а, б);
  if (р.равно) return null;
  if (р.почему === 'значения целиком')
    return `  ✗ ${имя}\n      было : ${JSON.stringify(р.было)}\n      стало: ${JSON.stringify(р.стало)}`;
  return `  ✗ ${имя}\n      ${р.почему}`;
}
