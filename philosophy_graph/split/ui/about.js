// Сгенерировано из philosophy_graph.html — правки вносить сюда, не в исходник.
import { DATA } from '../core/ns.js';

function собратьОПроекте() {
      const кол = {
        концепций: DATA.concepts.length, связей: DATA.relations.length,
        философов: DATA.philosophers.length, традиций: DATA.traditions.length,
        рубрик: DATA.rubrics.length, типов: DATA.relationTypes.length,
      };
      const годы = DATA.philosophers.map(p => p.birth).filter(г => typeof г === 'number');
      const ранний = Math.min(...годы), поздний = Math.max(...годы);
      const век = г => г < 0 ? Math.abs(г) + ' до н.э.' : String(г);

      const строка = (что, как) => `<tr><td>${что}</td><td>${как}</td></tr>`;

      return `
        <h2>Граф философских концепций</h2>
        <div class="about-lead">Карта понятий европейской философии и связей между
          ними: что из чего выросло, что чему противоречит, что на что похоже.</div>

        <h3>Что в базе</h3>
        <table>
          ${строка('Концепции', `${кол.концепций} — понятия, каждое принадлежит философу`)}
          ${строка('Связи', `${кол.связей} по ${кол.типов} типам: влияние, развитие, критика,
            противопоставление, предпосылка и другие`)}
          ${строка('Философы', `${кол.философов}, от ${век(ранний)} до ${век(поздний)}`)}
          ${строка('Традиции', `${кол.традиций} — школы и направления`)}
          ${строка('Рубрики', `${кол.рубрик} — разделы философии: онтология, этика и прочие`)}
        </table>

        <h3>Граф</h3>
        <table>
          ${строка('Щелчок по узлу', 'подсветить соседей; несмежные связи гаснут')}
          ${строка('Ctrl+щелчок', 'добавить узел или связь к выбору, повторный — снять')}
          ${строка('Двойной щелчок', 'открыть окно концепции')}
          ${строка('Щелчок по связи', 'открыть окно связи')}
          ${строка('Перетаскивание', 'сдвинуть узел; отпустите — он останется свободным')}
          ${строка('Колесо', 'масштаб; перетаскивание пустого места — сдвиг полотна')}
          ${строка('Наведение', 'подсказка с описанием узла или связи')}
          ${строка('Состояния', `выбранная концепция — жёлтый ободок, подсвеченная — белый
            потолще со свечением, обычная — тонкий белый, приглушённая — полупрозрачная`)}
        </table>

        <h3>Легенда слева</h3>
        <table>
          ${строка('Галочки', 'показать или скрыть философов, типы связей, рубрики, традиции')}
          ${строка('Заголовки разделов', 'свернуть или развернуть раздел')}
          ${строка('Щелчок по строке философа', `выбрать его на графе: концепции подсвечиваются,
            соседи по внешним связям остаются видны, прочее гаснет`)}
          ${строка('Ctrl+щелчок по строке', 'добавить философа к выбору')}
          ${строка('Двойной щелчок по строке', 'окно философа')}
          ${строка('Поиск', `раскрывается кнопкой; три вида — философ, концепция, связь.
            Связь ищется по двум концам, и второй сужает выбор первого`)}
          ${строка('Скрытая отбором', `находится и помечается; выбор показывает её ПОВЕРХ
            отбора, а в легенде появляется кнопка возврата`)}
        </table>

        <h3>Поиск пути</h3>
        <table>
          ${строка('Откуда и куда', 'выбор концепции из полного списка или печатью')}
          ${строка('Веса', 'сильные связи считаются более короткими')}
          ${строка('Направленность', 'идти только по стрелке связи')}
          ${строка('Хронология', 'режимы: строгий, умеренный, свободный и «без разрывов»')}
          ${строка('Без разрывов', `время идёт только в одну сторону. Если цель раньше
            источника, путь читается как родословная — «восходит к». Прочие режимы
            проверяют каждую связь по отдельности, поэтому путь может уйти вперёд на
            века и вернуться назад`)}
          ${строка('Описания пути', 'узлы и связи по порядку, с годами и традициями')}
        </table>

        <h3>Статистика</h3>
        <table>
          ${строка('39 видов', 'от простых счётчиков до метрик влияния и напряжения')}
          ${строка('Область счёта', 'по всему графу или только по видимой части')}
          ${строка('Нормировка', 'сырые числа или приведённые к общей шкале')}
          ${строка('Визуализировать размером', `узлы меняют размер по метрике; окно
            закрывается, а в легенде появляется кнопка сброса`)}
        </table>

        <!-- Раздел о панели контроля убран намеренно: у каждой её кнопки
             есть подсказка при наведении, и перечень здесь только устаревал
             бы вслед за панелью, ничего не добавляя. -->
      `;
    }

function openAboutModal() {
      const box = document.getElementById('aboutContent');
      if (box) box.innerHTML = собратьОПроекте();
      document.getElementById('aboutModal').classList.add('show');
    }

function closeAboutModal() {
      document.getElementById('aboutModal').classList.remove('show');
    }

function onAboutBackdropClick(ev) {
      if (ev.target && ev.target.id === 'aboutModal') closeAboutModal();
    }

export { closeAboutModal, onAboutBackdropClick, openAboutModal, собратьОПроекте };
