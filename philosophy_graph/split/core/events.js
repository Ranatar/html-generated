const СОБЫТИЯ_ШИНЫ = [
      'фильтры-применены',      // отбор пересчитан; вид пора обновить
      'данные-изменились',      // база правлена: добавили, удалили, переименовали
      'открыть-концепцию',      // щелчок по узлу просит окно концепции
      'открыть-связь',          // щелчок по связи просит окно связи
      'править-концепцию',      // shift-щелчок под admin
      'править-связь',
      'статистика-устарела',    // метрики пересчитаны; открытый вид пора обновить
      'закрыть-окна',           // просьба свернуть всё открытое
      'закрыть-статистику',     // наложение метрики просит убрать панель
      'концепция-выбрана-на-графе', // выбор с полотна доставлен просившему
      'сравнение-обновить',     // выбран участник сравнения концепций
      'переключить-вид',        // вид статистики просит показать другой вид
      'философы-выбраны',       // набор выбранных философов изменился
      'выделение-снято',        // на графе не осталось ничего выбранного
    ];

const подписчикиШины = new Map();

function подписаться(событие, дело) {
      if (!СОБЫТИЯ_ШИНЫ.includes(событие)) {
        console.error('шина: неизвестное событие при подписке —', событие);
        return;
      }
      if (!подписчикиШины.has(событие)) подписчикиШины.set(событие, []);
      подписчикиШины.get(событие).push(дело);
    }

function известить(событие, ...доводы) {
      if (!СОБЫТИЯ_ШИНЫ.includes(событие)) {
        console.error('шина: неизвестное событие —', событие);
        return;
      }
      for (const дело of подписчикиШины.get(событие) || []) {
        try { дело(...доводы); }
        catch (e) { console.error('шина: подписчик события «' + событие + '» упал —', e); }
      }
    }

export { СОБЫТИЯ_ШИНЫ, известить, подписаться, подписчикиШины };
